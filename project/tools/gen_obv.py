"""OBERVAVE's programs (firmware/src/eng_obv.c) from OberVave's own sources, kept as they are in tools/obervave/
(obv_params.h, obv_patches.h: OberVave 3.3.2 by zvenson, github.com/zvenson/obervave, commit 099ccd6, GPL-3.0-only).

  tools/gen_obv.py OUT.h

OberVave stores a program as its changes over the parameter defaults. Of its parameters the engine reads the voice's
(oscillators, filter, filter envelope, LFO, vintage, volume): those are packed here the same way (OBV_DEF, then per
program (index, value) pairs ended by 255). The rest of a program becomes BoopBox's own: the amp envelope (ATK DEC SUS
REL), MONO / UNISON, the glide, the arpeggiator and the effect sends, written as one preset_t per program."""
import math
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "obervave"

# a preset's name is how the browser and a project find it: the programs named as another engine's sound get "OB"
RENAME = {"DEEP BASS": "OB DEEP", "ENSEMBLE": "OB ENSEMBL", "FAT BASS": "OB FATBASS", "PLUCK BASS": "OB PLUCKBS",
          "PWM LEAD": "OB PWM LD", "SOFT KEYS": "OB SOFTKEY", "SUB BASS": "OB SUBBASS", "SYNC LEAD": "OB SYNC LD",
          "WARM PAD": "OB WARMPAD", "WURLI": "OB WURLI"}
BACK = {v: k for k, v in RENAME.items()}

# the parameters the engine reads, in this order (eng_obv.c OP_*)
VOICE = ["O1_WAVE", "O1_PW", "O1_LVL", "NOISE", "O2_WAVE", "O2_PW", "O2_LVL", "O2_SEMI", "SYNC", "XMOD", "ENV_O2",
         "O2_FINE", "CUTOFF", "RESO", "FENV_AMT", "KEYTRK", "FTYPE", "DRIVE", "VEL_FLT", "FA", "FD", "FS", "FR",
         "LFO_SHAPE", "LFO_RATE", "LFO_DELAY", "LFO_PHASE", "LFO_PITCH", "LFO_PWM", "LFO_FLT", "LFO_AMP",
         "LFO_PITCH_TO", "LFO_PWM_TO", "VINTAGE", "VOLUME", "FMORPH"]


def strip_comments(s):
    return re.sub(r"/\*.*?\*/", " ", s, flags=re.S)


def enums(text):
    """every enum's names -> values"""
    vals = {}
    for body in re.findall(r"enum\s*\{([^}]*)\}", text):
        n = 0
        for tok in [t.strip() for t in body.split(",") if t.strip()]:
            if "=" in tok:
                name, v = [x.strip() for x in tok.split("=")]
                n = int(v, 0) if re.match(r"^-?\d", v) else vals[v]
            else:
                name = tok
            vals[name] = n
            n += 1
    return vals


def main(out):
    params = strip_comments((SRC / "obv_params.h").read_text())
    patches = strip_comments((SRC / "obv_patches.h").read_text())
    ev = enums(params)
    ev["X"] = 255

    def val(tok):
        tok = tok.strip()
        return int(tok, 0) if re.match(r"^-?\d", tok) else ev[tok]

    # defaults: [P_X] = {"NAME", max, def, kind, cc}
    defs = {}
    for name, body in re.findall(r"\[P_(\w+)\]\s*=\s*\{([^}]*)\}", params):
        f = [x.strip() for x in body.split(",")]
        defs[name] = val(f[2])
    prog = {}
    for name, body in re.findall(r"static const uint8_t (PF_\w+)\[\]\s*=\s*\{([^}]*)\}", patches):
        toks = [t for t in body.replace("\n", " ").split(",") if t.strip()]
        v = [val(t) for t in toks]
        assert v[-1] == 255, name
        pairs = {}
        for i in range(0, len(v) - 1, 2):
            pairs[v[i]] = v[i + 1]
        prog[name] = pairs
    order = re.findall(r'\{"([^"]+)",\s*(PF_\w+)\}', patches[patches.index("FACT_VIBE[] ="):])
    vibe = order[:6]
    fact = re.findall(r'\{"([^"]+)",\s*(PF_\w+)\}', patches[patches.index("FACTORY[NFACT] ="):])
    progs = fact + vibe                                  # OberVave's 1..64, then its six VIBE programs (65..70)
    assert len(progs) == 70, len(progs)
    progs = [(RENAME.get(n, n), pf) for n, pf in progs]
    assert len({n for n, _ in progs}) == len(progs) and all(len(n) <= 10 for n, _ in progs)
    pid = {k: ev["P_" + k] for k in defs}

    def full(pf):
        p = {k: defs[k] for k in defs}
        for i, v in prog[pf].items():
            p[[k for k, n in pid.items() if n == i][0]] = v
        return p

    L = ["/* generated by tools/gen_obv.py from OberVave 3.3.2 (zvenson, GPL-3.0-only): do not edit */", "#pragma once",
         f"#define OBV_NPROG {len(progs)}u"]
    L.append("enum { " + ", ".join("OP_" + k for k in VOICE) + ", OP_N };")
    for pre, keys in (("OW_", ["W_OFF", "W_SAW", "W_PLS", "W_BOTH"]),
                      ("OF_", ["F_LP12", "F_HP12", "F_BP12", "F_NOTCH", "F_LP24", "F_SEM"]),
                      ("OL_", ["L_TRI", "L_SAW", "L_RAMP", "L_SQR", "L_SH", "L_RND"]),
                      ("OLP_", ["LP_SYNC", "LP_FREE", "LP_SPREAD"]), ("OTO_", ["TO_O1", "TO_O2", "TO_BOTH"])):
        L.append("enum { " + ", ".join(f"{pre}{k.split('_', 1)[1]} = {ev[k]}" for k in keys) + " };")
    L.append("static const uint8_t OBV_DEF[OP_N] = {" + ", ".join(str(defs[k]) for k in VOICE) + "};")
    data, offs = [], []
    for name, pf in progs:
        offs.append(len(data))
        for i, k in enumerate(VOICE):
            v = full(pf)[k]
            if v != defs[k]:
                data += [i, v]
        data.append(255)
    L.append(f"static const uint8_t OBV_SET[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        L.append("    " + ", ".join(str(x) for x in data[i:i + 24]) + ",")
    L.append("};")
    L.append(f"static const uint16_t OBV_OFF[OBV_NPROG] = {{{', '.join(str(o) for o in offs)}}};")
    L.append("static const char *const OBV_NAMES[OBV_NPROG + 1] = {" + ", ".join(f'"{n}"' for n, _ in progs) + ", 0};")

    # the rest of each program as BoopBox's preset
    def t_ms(v):                                         # OberVave's envelope times: 0.5 ms .. 10 s
        return 0.5 * 20000 ** (v / 127)

    def boop_t(v):                                       # params.c / gen_tables.py: 1 ms .. 10 s
        return max(0, min(127, int(round(127 * math.log(max(1.0, t_ms(v))) / math.log(10000)))))

    amode = {ev["A_OFF"]: 0, ev["A_UP"]: 1, ev["A_DOWN"]: 2, ev["A_UPDN"]: 3, ev["A_RND"]: 4, ev["A_PLAY"]: 5}
    adiv = {ev["D_4"]: 0, ev["D_8"]: 1, ev["D_8T"]: 4, ev["D_16"]: 2, ev["D_16T"]: 5, ev["D_32"]: 3, ev["D_32T"]: 3}
    L.append("static const preset_t OBV_PRESETS[OBV_NPROG] = {")
    for n, (name, pf) in enumerate(progs):
        p = full(pf)
        env = [boop_t(p["AA"]), boop_t(p["AD"]), p["AS"], boop_t(p["AR"])]
        mono = 1 if p["MODE"] == ev["M_MONO"] else 0
        send = lambda v: v // 2                          # (a send into BoopBox's shared effects, not their own)
        fx = f"FX(0, {send(p['CHO_MIX'])}, {send(p['DLY_MIX'])}, {send(p['REV_MIX'])})"
        xs = []
        if p["GLIDE"]:
            xs += ["P_GLIDE + 1", str(min(127, p["GLIDE"]))]
        if p["MODE"] == ev["M_UNISON"]:
            xs += ["P_VOICE + 1", "3", "P_DETUNE + 1", str(min(127, p["UNI_DET"]))]
        arp = ""
        if p["ARP_MODE"] != ev["A_OFF"]:
            arp = (f", ARP({amode[p['ARP_MODE']]}, {adiv[p['ARP_DIV']]}, {max(1, min(4, p['ARP_OCT']))}, "
                   f"{max(1, min(127, p['ARP_GATE']))})")
        x = f", XP({', '.join(xs)})" if xs else ""
        L.append(f'    {{"{name}", {{{n}, 0, 0, 0, 0, 0, 0, 0}}, {{{env[0]}, {env[1]}, {env[2]}, {env[3]}}}, 0, {mono}, '
                 f"{fx}{arp}{x}}},")
    L.append("};")
    # the sound browser's entries (ui.c BANK): each program once, under the kind its name says
    # one macro per kind, each at the end of its kind's group in ui.c BANK (the KIND view lists every kind once), with
    # its own trailing commas (a kind with no program is empty)
    for k in ["BASS", "KEYS", "ORGAN", "PAD", "LEAD", "PLUCK", "STAB", "FX"]:
        ent = [n for n, pf in progs if kind(BACK.get(n, n), full(pf), ev) == "BK_" + k]
        L.append(f"#define OBV_BANK_{k} " + "".join(f'{{BK_{k}, ENGI_OBV, "{n}"}}, ' for n in ent))
    Path(out).write_text("\n".join(L) + "\n")
    print(f"obervave: {len(progs)} programs, {len(data)} B of program data -> {out}")


def kind(name, p, ev):
    """ui.c BK_*: by the name first, then by what the program is"""
    words = name.replace("-", " ").split()

    def has(*k):
        return any(x in words for x in k)
    if has("KICK", "SNARE", "HIHAT", "CLAP", "ZAP", "WASH", "HIT", "NOISE"):
        return "BK_FX"
    if has("BASS", "BS", "SUB"):
        return "BK_BASS"
    if has("ORGN", "ORGAN"):
        return "BK_ORGAN"
    if has("KEYS", "EP", "PIANO", "WURLI", "CLAV", "RHODES"):
        return "BK_KEYS"
    if has("STAB", "BRASS", "HORN", "SECT"):
        return "BK_STAB"
    if has("LEAD", "LD"):
        return "BK_LEAD"
    if has("PLUCK", "BELL", "BELLS", "ARP", "SEQ"):
        return "BK_PLUCK"
    if has("PAD", "PD", "STRING", "STRINGS", "CHOIR", "SWEEP", "ENSEMBLE", "DRONE", "UNI", "AIR"):
        return "BK_PAD"
    if p["MODE"] in (ev["M_MONO"], ev["M_UNISON"]):
        return "BK_LEAD"
    return "BK_PAD" if p["AA"] > 40 else "BK_PLUCK"


if __name__ == "__main__":
    main(sys.argv[1])
